def test_disagreement_is_rendered_never_resolved(estate_root: Path) -> None:
    estate = catalog.derive(estate_root)
    assert [d.member for d in estate.disagreements] == ["bmad-method-test-architecture-enterprise"]
    versions = estate.disagreements[0].versions
    assert versions[catalog.REGISTER_RELPATH.as_posix()] == "1.24.0"
    assert versions["pixi.toml"] == "1.26.0"
    text = catalog.render(estate, today=date(2026, 9, 29))
    assert "### Sources disagree" in text
    assert "`bmad-method-test-architecture-enterprise` | `_bmad-output/" in text
    assert "→ 1.24.0" in text and "→ 1.26.0" in text
    assert "never this generator's" in text


def test_render_carries_header_sections_and_digests(estate_root: Path) -> None:
    estate = catalog.derive(estate_root)
    text = catalog.render(estate, today=date(2026, 9, 29))
    assert text.startswith("# local-recipes — the BMAD estate, derived")
    assert "Generated: 2026-09-29" in text
    assert catalog.REGENERATE_COMMAND in text
    assert catalog.DETECTOR_NAME in text
    for heading in (
        "## 1. Installed core and modules",
        "## 2. Skills by family",
        "## 3. BMAD phases and sequence",
        "## 4. The bmad-suite roster",
        "## 5. Pins",
        "## 6. Marshal ↔ bmad-loop harness",
        "## 7. The release cadence",
        "## 8. Pipeline truth",
    ):
        assert heading in text, heading
    assert "`6.12.0` — `installShims: false`" in text
    assert f"### {catalog.FAMILY_PERSONAS} (1)" in text
    assert f"### {catalog.FAMILY_BMB} (1)" in text
    assert "| `bmad-method` | 6.12.0 | installer-tree | wield (substrate) | all stations |" in text
    assert "Deprecated catalog rows" in text and "`bmad-method-wds-expansion`" in text
    assert "| `bmad-loop` | `feature.guild.dependencies` | `>=0.12.0` |" in text
    assert "Supported bmad-loop range: `>=0.11.0,<0.13`" in text
    assert "- 1. Doctor — detect." in text
    assert "with no `SKILL.md` (not skills): `shared`" in text
    recorded = catalog.recorded_digests(text)
    assert recorded == catalog.digests(estate)
    assert set(recorded) == set(catalog.SECTION_SOURCES)


def test_write_then_check_is_clean_and_prose_is_exempt(estate_root: Path) -> None:
    target = catalog.write(estate_root)
    assert target == estate_root / catalog.CATALOG_RELPATH
    assert catalog.check(estate_root) == []
    # A prose-only change (the generation date, a reworded sentence) is not drift.
    edited = target.read_text(encoding="utf-8").replace("Generated: ", "Rendered on: ")
    target.write_text(edited, encoding="utf-8")
    assert catalog.check(estate_root) == []


def test_check_names_the_drifted_section_and_its_source(estate_root: Path) -> None:
    catalog.write(estate_root)
    manifest = estate_root / catalog.MANIFEST_RELPATH
    manifest.write_text(
        _MANIFEST.replace("version: 6.12.0\n  installDate", "version: 6.13.0\n  installDate"), encoding="utf-8"
    )
    findings = catalog.check(estate_root)
    assert len(findings) == 1
    assert "section `installed` drifted" in findings[0]
    assert catalog.MANIFEST_RELPATH.as_posix() in findings[0]
    _skill(estate_root, "bmad-walkthrough", "Walk the user through a change.")
    findings = catalog.check(estate_root)
    assert {f.split("`")[1] for f in findings} == {"installed", "skills"}


