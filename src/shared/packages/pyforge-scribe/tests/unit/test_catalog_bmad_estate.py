def test_pipeline_truth_input_adds_stage_columns(estate_root: Path, tmp_path: Path) -> None:
    truth = tmp_path / "truth.json"
    truth.write_text(
        json.dumps(
            {
                "packages": [
                    {
                        "name": "bmad-method",
                        "install_class": "installer-tree",
                        "recipe": {"value": "6.12.0", "ok": True, "detail": ""},
                        "channel": {"value": "6.12.0", "ok": True, "detail": ""},
                        "installed": {"value": "6.12.0", "ok": True, "detail": ""},
                        "wired": {"value": "present", "ok": True, "detail": ""},
                        "upstream_npm": {"value": "6.12.0", "ok": True, "detail": ""},
                        "upstream_github": {"value": "v6.12.0", "ok": True, "detail": ""},
                        "drifts": [],
                    }
                ]
            }
        ),
        encoding="utf-8",
    )
    estate = catalog.derive(estate_root, pipeline_truth=truth)
    assert estate.pipeline_truth["bmad-method"]["wired"] == "present"
    text = catalog.render(estate)
    assert "| `bmad-method` | 6.12.0 | 6.12.0 | 6.12.0 | present | 6.12.0 | v6.12.0 | — |" in text
    with pytest.raises(catalog.CatalogSourceError, match="pipeline-truth"):
        catalog.derive(estate_root, pipeline_truth=tmp_path / "absent.json")


def test_cli_write_check_and_exit_codes(estate_root: Path) -> None:
    printed = runner.invoke(app, ["catalog", "bmad-estate", "--root", str(estate_root)])
    assert printed.exit_code == 0, printed.output
    assert "## 4. The bmad-suite roster" in printed.output

    written = runner.invoke(app, ["catalog", "bmad-estate", "--root", str(estate_root), "--write"])
    assert written.exit_code == 0, written.output
    assert (estate_root / catalog.CATALOG_RELPATH).is_file()

    clean = runner.invoke(app, ["catalog", "bmad-estate", "--root", str(estate_root), "--check"])
    assert clean.exit_code == 0, clean.output
    assert "ok -- the catalog matches its sources" in clean.output

    (estate_root / catalog.HARNESS_RELPATH).write_text(_HARNESS.replace("<0.13", "<0.14"), encoding="utf-8")
    drifted = runner.invoke(app, ["catalog", "bmad-estate", "--root", str(estate_root), "--check"])
    assert drifted.exit_code == 1, drifted.output
    assert "section `harness` drifted" in drifted.output

    both = runner.invoke(app, ["catalog", "bmad-estate", "--root", str(estate_root), "--write", "--check"])
    assert both.exit_code == 2

    (estate_root / catalog.HELP_CSV_RELPATH).unlink()
    broken = runner.invoke(app, ["catalog", "bmad-estate", "--root", str(estate_root), "--check"])
    assert broken.exit_code == 2, broken.output
    assert "could-not-run" in broken.output


def test_cli_output_option_targets_another_file(estate_root: Path, tmp_path: Path) -> None:
    target = tmp_path / "elsewhere.md"
    written = runner.invoke(
        app, ["catalog", "bmad-estate", "--root", str(estate_root), "--write", "--output", str(target)]
    )
    assert written.exit_code == 0, written.output
    assert target.is_file()
    checked = runner.invoke(
        app, ["catalog", "bmad-estate", "--root", str(estate_root), "--check", "--output", str(target)]
    )
    assert checked.exit_code == 0, checked.output
