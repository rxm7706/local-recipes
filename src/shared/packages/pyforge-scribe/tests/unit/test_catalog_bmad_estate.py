def _skill(root: Path, name: str, description: str, *, nested: bool = False) -> None:
    if nested:
        target = root / catalog.SKILLS_RELPATH / name / "active" / name
    else:
        target = root / catalog.SKILLS_RELPATH / name
    target.mkdir(parents=True)
    (target / "SKILL.md").write_text(
        f"---\nname: {name}\ndescription: {description}\n---\n\n# {name}\n", encoding="utf-8"
    )


