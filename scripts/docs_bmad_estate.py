#!/usr/bin/env python3
"""Generator door: ``docs/reference/bmad-estate-llms-full.md`` (doctor Story 30.4,
spec-pyforge-doctor CAP-84; the catalog itself is scribe Story 24.1/24.2, spec-pyforge-scribe CAP-32).

The page's generator is scribe's own CLI, ``scribe catalog bmad-estate``. ``docs-currency``
runs only a ``scripts/docs_*.py`` generator (doctor Story 40.2), so ``docs/map.yaml`` could not
name one for this page and reported it as a registry gap. This script is that door and nothing
more. ``--check`` is ``bmad-estate-check``'s own verdict (``scripts/bmad_estate_check.py``
``run_check``, which already tells a scribe CLI that cannot start from real drift); without it,
the page is regenerated by the scribe CLI entry (never ``pyforge.scribe`` internals), run
through this interpreter.

Usage::

    python scripts/docs_bmad_estate.py                    # regenerate (scribe catalog bmad-estate --write)
    python scripts/docs_bmad_estate.py --check            # exit 0 current, 1 stale, 2 could not run
    python scripts/docs_bmad_estate.py --check --root R   # judge another checkout's tree
"""

from __future__ import annotations

import argparse
import importlib.util
import subprocess
import sys
from pathlib import Path

# The sibling detector is imported from this script's own folder, which Python leaves off sys.path under
# PYTHONSAFEPATH / -P / -I; the other docs_*.py generators guard the same way.
sys.path.insert(0, str(Path(__file__).resolve().parent))

import bmad_estate_check  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PREFIX = "[docs-bmad-estate]"


def write_command(root: Path) -> list[str]:
    """The scribe CLI call that regenerates the page, run by this interpreter."""
    return [sys.executable, "-m", "pyforge.scribe.cli", "catalog", "bmad-estate", "--write", "--root", str(root)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Report staleness without writing.")
    parser.add_argument("--root", type=Path, default=ROOT, help="Repository root (default: this checkout).")
    args = parser.parse_args(argv)
    if args.check:
        code, lines = bmad_estate_check.run_check(args.root)
        for line in lines:
            print(line)
        return code
    if importlib.util.find_spec("pyforge.scribe") is None:
        print(f"{PREFIX} could-not-run: `pyforge.scribe` is not importable here ({sys.executable})")
        return 2
    try:
        proc = subprocess.run(write_command(args.root), capture_output=True, text=True, check=False)
    except OSError as exc:
        print(f"{PREFIX} could-not-run: {exc}")
        return 2
    output = (proc.stdout + proc.stderr).strip()
    if output:
        print(output)
    return 0 if proc.returncode == 0 else 2


if __name__ == "__main__":
    sys.exit(main())
